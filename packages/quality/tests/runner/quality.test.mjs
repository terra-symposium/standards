test('performance pattern findings are reported as advisory and do not fail quality', () => {
	const root = mkdtempSync(join(tmpdir(), 'terra-quality-performance-advisory-'));
	writeFileSync(
		join(root, 'main.ts'),
		'type Row = { id: number };\ntype RowRecord = { id: number };\nconst rows: Row[] = [];\nconst records: RowRecord[] = [];\nconst matches = rows.map((row) => records.find((record) => record.id === row.id));\nvoid matches;\n',
	);
	const cfg = createQualityCfg({
		root,
		sourceRoots: ['.'],
		extensions: ['.ts'],
		performancePatterns: { extensions: ['.ts'] },
		enabledChecks: {
			format: false,
			lint: false,
			knip: false,
			'dead-code': false,
			type: false,
			command: false,
			recommend: false,
			import: false,
			document: false,
			name: false,
			alias: false,
			forward: false,
			diff: false,
			'performance-patterns': true,
		},
	});
	const errs = [];
	const previousExitCode = process.exitCode;
	const previousConsoleErr = console.error;
	process.exitCode = 0;
	console.error = (...args) => errs.push(args.join(' '));
	try {
		runQualityCli(cfg, ['quality', '--all', '--skip-commands', '--skip-recommendations', '--report-json', 'quality-report.json']);
		assert.equal(process.exitCode, 0);
		assert.ok(errs.some(line => /Consider precomputing a Map or Set/u.test(line)));
		assert.deepEqual(
			JSON.parse(readFileSync(join(root, 'quality-report.json'), 'utf8')).checks.find(check => check.name === 'performance-patterns'),
			{ name: 'performance-patterns', status: 'passed', findings: 0 },
		);
		assert.equal(performancePatternFindings(cfg).length, 1);
	} finally {
		console.error = previousConsoleErr;
		process.exitCode = previousExitCode;
	}
});
