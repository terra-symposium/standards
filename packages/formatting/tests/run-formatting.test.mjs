//////////////////////////////////////////////////*/

test('format fix leaves source unchanged when Prettier is unavailable', t => {
	const root = mkdtempSync(join(tmpdir(), 'terra-formatting-missing-prettier-'));
	t.after(() => rmSync(root, { recursive: true, force: true }));
	const source = join(root, 'src', 'config.ts');
	mkdirSync(join(root, 'src'));
	const original = 'export const config = {\n\tenabled: true,\n\toptions: {\n\t\tmode: "safe"\n\t}\n};\n';
	writeFileSync(source, original);
	const status = runFormatting({ root, sourceRoots: [join(root, 'src')], extensions: ['.ts'], tools: { prettier: 'terra-prettier-that-does-not-exist' } }, { fix: true });
	assert.notEqual(status, 0);
	assert.equal(readFileSync(source, 'utf8'), original);
});

test('format fix restores source when Prettier rejects a candidate', t => {
	const root = mkdtempSync(join(tmpdir(), 'terra-formatting-failed-prettier-'));
	t.after(() => rmSync(root, { recursive: true, force: true }));
	const source = join(root, 'src', 'config.ts');
	const prettier = join(root, 'prettier-fails-after-version');
	mkdirSync(join(root, 'src'));
	const original = 'export const config = {\n\tenabled: true,\n\toptions: {\n\t\tmode: "safe"\n\t}\n};\n';
	writeFileSync(source, original);
	writeFileSync(prettier, '#!/usr/bin/env node\nif (process.argv.includes("--version")) process.stdout.write("prettier 3\\n");\nelse process.exit(2);\n');
	chmodSync(prettier, 0o755);
	const status = runFormatting({ root, sourceRoots: [join(root, 'src')], extensions: ['.ts'], tools: { prettier } }, { fix: true });
	assert.equal(status, 2);
	assert.equal(readFileSync(source, 'utf8'), original);
});

test('format checking includes configured Astro sources', t => {
	const root = mkdtempSync(join(tmpdir(), 'terra-formatting-astro-'));
	t.after(() => rmSync(root, { recursive: true, force: true }));
	const src = join(root, 'src');
	const tsSource = join(src, 'config.ts');
	const astroSource = join(src, 'page.astro');
	const marker = join(root, 'prettier-args.json');
	const prettier = join(root, 'recording-prettier.mjs');
	mkdirSync(src);
	writeFileSync(tsSource, 'export const enabled = true;\n');
	writeFileSync(astroSource, '<main />\n');
	writeFileSync(
		prettier,
		`#!/usr/bin/env node\nimport { appendFileSync } from 'node:fs';\nif (process.argv.includes('--version')) process.stdout.write('prettier 3\\n');\nelse appendFileSync(${JSON.stringify(marker)}, JSON.stringify(process.argv.slice(2)) + '\\n');\n`,
	);
	chmodSync(prettier, 0o755);
	const status = runFormatting({ root, sourceRoots: [src], extensions: ['.ts', '.astro'], tools: { prettier } }, { fix: true });
	assert.equal(status, 0);
	const invocations = readFileSync(marker, 'utf8')
		.trim()
		.split('\n')
		.map(line => JSON.parse(line));
	const args = invocations[0];
	assert.ok(args.includes('--write'));
	assert.ok(args.includes(tsSource));
	assert.ok(args.includes(astroSource));
	assert.ok(invocations[1].includes('--check'));
});

test('formatting preserves generated source files while formatting authored sources', t => {
	const root = mkdtempSync(join(tmpdir(), 'terra-formatting-generated-source-'));
	t.after(() => rmSync(root, { recursive: true, force: true }));
	const src = join(root, 'src');
	const artifactFile = join(src, 'course-data.js');
	const authored = join(src, 'consumer.js');
	const marker = join(root, 'prettier-args.json');
	const prettier = join(root, 'recording-prettier.mjs');
	mkdirSync(src);
	writeFileSync(artifactFile, '// Generated by the course catalog.\nexport const courses = [{ id: "one" }];\n');
	writeFileSync(authored, 'export const label = "ready";\n');
	writeFileSync(
		prettier,
		`#!/usr/bin/env node\nimport { appendFileSync } from 'node:fs';\nif (process.argv.includes('--version')) process.stdout.write('prettier 3\\n');\nelse appendFileSync(${JSON.stringify(marker)}, JSON.stringify(process.argv.slice(2)) + '\\n');\n`,
	);
	chmodSync(prettier, 0o755);
	const status = runFormatting({ root, sourceRoots: [src], extensions: ['.js'], tools: { prettier } }, { fix: true });
	assert.equal(status, 0);
	const args = readFileSync(marker, 'utf8')
		.trim()
		.split('\n')
		.map(line => JSON.parse(line))
		.flat();
	assert.ok(args.includes(authored));
	assert.equal(args.includes(artifactFile), false);
	assert.equal(readFileSync(artifactFile, 'utf8'), '// Generated by the course catalog.\nexport const courses = [{ id: "one" }];\n');
});

test('format fix retries when the first Prettier write does not stabilize output', t => {
	const root = mkdtempSync(join(tmpdir(), 'terra-formatting-retry-'));
	t.after(() => rmSync(root, { recursive: true, force: true }));
	const src = join(root, 'src');
	const source = join(src, 'main.ts');
	const writes = join(root, 'prettier-write-count.txt');
	const prettier = join(root, 'recording-prettier.mjs');
	const canonical = "export const value = 'ready';\n";
	mkdirSync(src);
	writeFileSync(source, "export const value='ready'\n");
	writeFileSync(writes, '0');
	writeFileSync(
		prettier,
		`#!/usr/bin/env node
import { readFileSync, writeFileSync } from 'node:fs';
if (process.argv.includes('--version')) process.stdout.write('prettier 3\\n');
else if (process.argv.includes('--write')) {
	const count = Number(readFileSync(${JSON.stringify(writes)}, 'utf8')) + 1;
	writeFileSync(${JSON.stringify(writes)}, String(count));
	if (count > 1) writeFileSync(${JSON.stringify(source)}, ${JSON.stringify(canonical)});
} else if (process.argv.includes('--check') && readFileSync(${JSON.stringify(source)}, 'utf8') !== ${JSON.stringify(canonical)}) process.exitCode = 1;
`,
	);
	chmodSync(prettier, 0o755);
	const status = runFormatting({ root, sourceRoots: [src], extensions: ['.ts'], tools: { prettier } }, { fix: true });
	assert.equal(status, 0);
	assert.equal(readFileSync(source, 'utf8'), canonical);
	assert.equal(readFileSync(writes, 'utf8'), '2');
});
