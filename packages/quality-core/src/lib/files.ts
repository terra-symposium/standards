/**
 * Discovers regular files under configured roots without scanning Git-ignored artifacts or symbolic links.
 *
 * @param cfg Quality configuration containing roots, extensions, explicit exclusions, and the repository's Git ignore rules.
 *
 * @return Sorted absolute paths for supported files in scope that are not Git-ignored.
 */
function sourceCandidates(cfg: QualityCfg): string[] {
	const roots = [...cfg.sourceRoots, ...(cfg.includeRoots ?? [])];
	const exts = new Set(cfg.extensions);
	const skippedFiles = new Set((cfg.skippedFiles ?? []).map(f => resolve(cfg.root, f)));
	const files: string[] = [];
	/**
	 * Checks an encountered directory against configured skip paths.
	 *
	 * @param dir Absolute directory path being considered for traversal.
	 *
	 * @return Whether the directory matches a configured skipped path.
	 */
	const isSkippedDir = (dir: string): boolean => {
		const repoPath = relative(cfg.root, dir);
		return (cfg.skippedDirectories ?? []).some(s => {
			const norm = normalize(s.replaceAll('\\', '/'));
			if (!norm || norm === '.') return false;
			if (!norm.includes(sep)) return basename(dir) === norm;
			const skippedPath = resolve(cfg.root, norm);
			return dir === skippedPath || dir.startsWith(`${skippedPath}${sep}`) || repoPath === norm;
		});
	};
	/**
	 * Applies configured and built-in path exclusions to a discovered candidate.
	 *
	 * @param file Absolute path of a candidate source file.
	 *
	 * @return Whether the candidate is inside an excluded directory or file path.
	 */
	const isSkippedRootFile = (file: string): boolean => {
		if (skippedFiles.has(resolve(file))) return true;
		for (let dir = dirname(resolve(file)); ; dir = dirname(dir)) {
			if (SCAN_PRUNED_DIRS.has(basename(dir)) || isSkippedDir(dir)) return true;
			if (dir === cfg.root || dirname(dir) === dir) return false;
		}
	};
	/**
	 * Adds eligible files from one configured root to the source inventory.
	 *
	 * @param dir Absolute root or nested directory to scan.
	 */
	const walk = (dir: string): void => {
		if (!existsSync(dir)) return;
		const entry = lstatSync(dir);
		// Pass regular paths to formatters and analyzers; a symlink alias may target an already-scanned file.
		if (entry.isSymbolicLink()) return;
		if (entry.isFile()) {
			if (!isSkippedRootFile(dir) && exts.has(dir.slice(dir.lastIndexOf('.')))) files.push(dir);
			return;
		}
		if (!entry.isDirectory() || SCAN_PRUNED_DIRS.has(basename(dir)) || isSkippedDir(dir)) return;
		for (const e of readdirSync(dir, { withFileTypes: true })) {
			if (e.isDirectory()) {
				if (!SCAN_PRUNED_DIRS.has(e.name)) walk(join(dir, e.name));
				continue;
			}
			if (!e.isFile()) continue;
			const path = join(dir, e.name);
			if (!skippedFiles.has(resolve(path)) && exts.has(e.name.slice(e.name.lastIndexOf('.')))) files.push(path);
		}
	};
	for (const root of roots) walk(root);
	const candidates = files.sort((a, b) => a.localeCompare(b));
	if (!candidates.length) return candidates;
	const gitPaths = candidates.map(file => relative(cfg.root, file)).filter(file => file && file !== '..' && !file.startsWith(`..${sep}`));
	if (!gitPaths.length) return candidates;
	try {
		const ignoredPaths = new Set(
			execFileSync('git', ['check-ignore', '--stdin', '-z'], { cwd: cfg.root, encoding: 'utf8', input: `${gitPaths.join('\0')}\0`, maxBuffer: 32 * 1024 * 1024, stdio: ['pipe', 'pipe', 'ignore'] })
				.split('\0')
				.filter(Boolean)
				.map(file => resolve(cfg.root, file)),
		);
		return candidates.filter(file => !ignoredPaths.has(resolve(file)));
	} catch (err) {
		const status = err && typeof err === 'object' && 'status' in err ? err.status : undefined;
		if (status === 1 || status === 128) return candidates;
		throw err;
	}
}

/**
 * Discovers authored source under the configured roots using the shared program classifier.
 *
 * @param cfg Quality configuration containing roots, extensions, and excluded paths.
 *
 * @return Sorted absolute paths for files that belong to the configured source scope.
 */
export function srcFiles(cfg: QualityCfg): string[] {
	return sourceCandidates(cfg).filter(isProgramSource);
}

/**
 * Finds code-like files rejected by the shared classifier as captured content or generated bundles.
 *
 * @param cfg Quality configuration containing roots, extensions, and excluded paths.
 *
 * @return Sorted absolute paths for non-program files with JavaScript or TypeScript suffixes.
 */
export function nonProgramSrcFiles(cfg: QualityCfg): string[] {
	return sourceCandidates(cfg).filter(path => JAVASCRIPT_SOURCE_EXTS.test(path) && !isProgramSource(path));
}

/**
 * Returns configured source files changed in the working tree, including untracked files.
 *
 * @param cfg Quality configuration whose repository root is used to query Git.
 *
 * @return Sorted configured source files that are changed or untracked in the working tree.
 */
export function workingSrcFiles(cfg: QualityCfg): string[] {
	const changed = new Set(
		execFileSync('git', ['diff', '--name-only', '--diff-filter=ACMR'], { cwd: cfg.root, encoding: 'utf8' })
			.concat(execFileSync('git', ['ls-files', '--others', '--exclude-standard'], { cwd: cfg.root, encoding: 'utf8' }))
			.split('\n')
			.filter(Boolean)
			.map(p => join(cfg.root, p)),
	);
	return srcFiles(cfg).filter(f => changed.has(f));
}

/**
 * Converts an absolute file path into the repository-relative path shown in diagnostics.
 *
 * @param cfg Quality configuration defining the repository root.
 * @param fileName Absolute path to the source file.
 *
 * @return A repository-relative path, or the basename when the path is already outside the root.
 */
export function displayPath(cfg: QualityCfg, fileName: string): string {
	return relative(cfg.root, fileName) || basename(fileName);
}

/**
 * Tests whether a path currently resolves to a regular file.
 *
 * @param path Filesystem path to inspect.
 *
 * @return `true` when the path exists and is a file; otherwise `false`.
 */
export function isFile(path: string): boolean {
	try {
		return statSync(path).isFile();
	} catch {
		return false;
	}
}
