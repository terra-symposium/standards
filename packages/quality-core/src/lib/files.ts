// API
import { basename, dirname, join, normalize, relative, resolve, sep } from 'node:path';
import { execFileSync } from 'node:child_process';
import { existsSync, lstatSync, readFileSync, readdirSync, statSync } from 'node:fs';

// TYPES
import type { QualityCfg } from '../types.js';

/*//////////////////////////////////////////////////
CONFIG
//////////////////////////////////////////////////*/
const BFROM_S_S_U_REGEX = /\bfrom\s*['"][^'"]+['"]\s*;?/u;

const SCAN_PRUNED_DIRS = new Set([
	'.git',
	'.pnpm',
	'node_modules',
	'.venv',
	'venv',
	'.tox',
	'.nox',
	'__pycache__',
	'dist',
	'build',
	'.build',
	'target',
	'coverage',
	'results',
	'test-results',
	'.next',
	'.astro',
	'.sanity',
	'.netlify',
	'.cache',
	'.output',
	'.vercel',
	'.nuxt',
	'.husky',
]);
const JAVASCRIPT_SOURCE_EXTS = /\.(?:cjs|mjs|js|jsx|cts|mts|ts|tsx)$/u;
// terra-quality-ignore single-use -- Compile the declaration detector once for repeated file classification.
const CODE_DECLARATION =
	/^\s*(?:#!|\/\/|\/\*|\*|import\b|export\b|(?:async\s+)?function\b|class\b|interface\b|type\b|enum\b|namespace\b|declare\b|const\b|let\b|var\b|return\b|if\b|for\b|while\b|switch\b|try\b|throw\b|await\b|<>|<\/?[A-Za-z][\w.:-]*(?:\s|\/?>))/mu;
// terra-quality-ignore single-use -- Compile the expression detector once for repeated file classification.
const CODE_EXPR =
	/(?:=>|\b(?:async\s+)?function\s*\(|\b(?:const|let|var)\s+[$\w]+\s*=|\bexport\s*\{|\bimport\s*\(|\{[^\n{}]*\}|;\s*(?:\/\/[^\n]*)?\n|^\s*(?:void|new|delete|console|window|document|process|globalThis|module|exports|require)\b)/mu;
// terra-quality-ignore single-use -- Compile the generated-data detector once for repeated file classification.
const GEN_DATA_ASSIGNMENT = /^(?:window|globalThis)\.[A-Z_$][\w$]*\s*=\s*(?:\{|\[)/u;
// terra-quality-ignore single-use -- Compile the minified-bundle detector once for repeated file classification.
const MINIFIED_BUNDLE_ENTRY = /^(?:!function\s*\(|(?:self\.)?webpackJsonp\b)/iu;
// terra-quality-ignore single-use -- Compile the generated-bundle filename detector once for repeated file classification.
const GEN_BUNDLE_NAME = /^(?:bundle|vendor|runtime|polyfills)(?:[.-][\w-]+)?(?:\.min)?\.(?:cjs|mjs|js)$/iu;
// terra-quality-ignore single-use -- Compile the persona attachment path detector once for repeated file classification.
const GEM_ATTACHMENT_PATH_REGEX = /(?:^|\/)\.agents\/personas\/gems\//u;

/**
 * Detects generated-source notices in the leading comment block.
 *
 * @param sourceText Contents of a source file.
 *
 * @return Whether the file identifies itself as generated or not manually editable.
 */
export function hasGeneratedSourceHeader(sourceText: string): boolean {
	return /@generated\b|\b(?:this file\s+)?(?:has been\s+)?generated by\b|\bdo not edit\b/iu.test(
		sourceText.replace(/^\uFEFF/u, '').match(/^(?:#![^\r\n]*(?:\r?\n|$))?(?:[ \t]*(?:\/\*[\s\S]*?\*\/|\/\/[^\r\n]*)(?:\r?\n|$))+/u)?.[0] ?? '',
	);
}

// terra-quality-ignore single-use -- Keep the documented withoutStaticImports declaration so its parameter and return contract remains attached.
/**
 * Removes static import statements before checking whether a source-suffixed export contains executable code.
 *
 * @param source Text of the candidate JavaScript or TypeScript file.
 *
 * @return The file body without static import declarations.
 */
function withoutStaticImports(source: string): string {
	const lines = source.split(/(?<=\n)/u);
	let body = '';
	let inImport = false;
	let hasStaticImport = false;
	for (const line of lines) {
		const trimmed = line.trim();
		if (inImport) {
			if (BFROM_S_S_U_REGEX.test(trimmed)) inImport = false;
			continue;
		}
		if (/^\s*import\s+(?!\()/u.test(line)) {
			hasStaticImport = true;
			if (!BFROM_S_S_U_REGEX.test(trimmed) && !/^import\s*['"][^'"]+['"]\s*;?/u.test(trimmed)) inImport = true;
			continue;
		}
		body += line;
	}
	return body.trim() ? body : hasStaticImport ? '' : source;
}

/**
 * Keeps captured prose, archived Gem attachments, and generated assets out of the
 * program-source set when upstream files use JavaScript or TypeScript suffixes.
 *
 * @param path Candidate source file discovered from the configured extensions.
 *
 * @return Whether the file has the shape of authored JavaScript or TypeScript source.
 */
function isProgramSource(path: string): boolean {
	if (!JAVASCRIPT_SOURCE_EXTS.test(path)) return true;
	if (GEM_ATTACHMENT_PATH_REGEX.test(path.split(sep).join('/'))) return false;
	const text = readFileSync(path, 'utf8');
	if (GEN_BUNDLE_NAME.test(basename(path)) && Buffer.byteLength(text) >= 100_000) return false;
	const firstLine = text.split(/\r?\n/u, 1)[0]?.trim() ?? '';
	if (GEN_DATA_ASSIGNMENT.test(firstLine) || (firstLine.length > 10_000 && MINIFIED_BUNDLE_ENTRY.test(firstLine))) return false;
	const body = withoutStaticImports(text);
	if (CODE_DECLARATION.test(body)) return true;
	if (CODE_EXPR.test(body)) return true;
	return text.trim().length === 0 || (body.trim().length === 0 && /^\s*import\b/mu.test(text));
}

